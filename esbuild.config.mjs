import esbuild from 'esbuild';
import process from 'process';
import { builtinModules } from 'node:module';
import { readFileSync } from 'node:fs';

// main.js is the only file users receive, so bundled licenses travel inside it.
const thirdPartyNotices = readFileSync('THIRD_PARTY_NOTICES', 'utf8');

const banner = `/*
THIS IS A GENERATED/BUNDLED FILE BY ESBUILD
if you want to view the source, please visit the github repository of this plugin

${thirdPartyNotices}
*/
`;

const prod = process.argv[2] === 'production';

const context = await esbuild.context({
	banner: {
		js: banner,
	},
	entryPoints: ['src/main.ts'],
	bundle: true,
	external: [
		'obsidian',
		'electron',
		'@codemirror/autocomplete',
		'@codemirror/collab',
		'@codemirror/commands',
		'@codemirror/language',
		'@codemirror/lint',
		'@codemirror/search',
		'@codemirror/state',
		'@codemirror/view',
		'@lezer/common',
		'@lezer/highlight',
		'@lezer/lr',
		...builtinModules,
	],
	format: 'cjs',
	target: 'es2021',
	// Inline WASM encoders into main.js; Obsidian plugins ship as a single file.
	loader: { '.wasm': 'binary' },
	logLevel: 'info',
	logOverride: {
		// The WASM glue reads import.meta.url, which encoders/webp.ts makes unused.
		'empty-import-meta': 'silent',
	},
	sourcemap: prod ? false : 'inline',
	treeShaking: true,
	outfile: 'main.js',
	minify: prod,
});

if (prod) {
	await context.rebuild();
	process.exit(0);
} else {
	await context.watch();
}
